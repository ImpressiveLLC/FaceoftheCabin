def test_a_stream_capture_failure_fails_the_run_kills_the_child_and_keeps_evidence(env, monkeypatch):
    incoming(env, "run-a")
    real = rc._write_chunk
    calls = {"n": 0}

    def failing(sink, chunk):
        calls["n"] += 1
        if sink.name.endswith("train.stdout"):
            raise OSError("synthetic disk write failure")
        return real(sink, chunk)

    monkeypatch.setattr(rc, "_write_chunk", failing)
    run_dir, bundle, manifest = run(env, "run-a")
    assert (manifest["status"], manifest["stage"]) == ("failed", "trainer_started")
    assert "synthetic disk write failure" in manifest["capture_error"]
    events = [json.loads(line) for line in (run_dir / "events.jsonl").read_text(encoding="utf-8").split("\n") if line]
    assert any(e["event"] == "stream_error" and e["stream"] == "stdout" for e in events)
    assert events[-1]["event"] == "exit"
    assert (run_dir / rc.MANIFEST).is_file() and (run_dir / rc.BUNDLE).is_file()


