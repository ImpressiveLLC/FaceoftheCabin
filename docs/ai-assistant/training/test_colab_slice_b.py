def make_run(store, run_id, *, total=4, chunks=(2, 4), chain="c", skipped=0, losses=None, bindings=None,
             adapter=b"adapter"):
    """A synthetic committed run, built through resumable.commit, with the evidence compare() reads."""
    from test_resumable import BINDINGS
    bindings = dict(bindings or BINDINGS, total_steps=total)
    losses = losses if losses is not None else {s: (2.0 - 0.1 * s, 1e-4 / s) for s in range(1, total + 1)}
    previous = 0
    for i, step in enumerate(chunks):
        d = store.parent / f"stage-{run_id}-{step}-{i}"
        d.mkdir(parents=True)
        (d / "adapter_model.safetensors").write_bytes(adapter)
        (d / "adapter_config.json").write_text("{}")
        history = [{"step": s, "loss": l, "learning_rate": lr} for s, (l, lr) in sorted(losses.items()) if s <= step]
        (d / "trainer_state.json").write_text(json.dumps({"global_step": step, "log_history": history}))
        for name in ("optimizer.pt", "scheduler.pt", "rng_state.pth"):
            (d / name).write_bytes(name.encode())
        rs.commit(d, store, run_id=run_id, global_step=step, total_steps=total, optimizer_updates=step - skipped,
                  skipped_updates=skipped, bindings=bindings, cursor={"resumed_from_step": previous},
                  evidence={"input_trace": {"sha256_chain": f"{chain}-{step}", "micro_batches_total": 4 * step,
                                            "micro_batches_this_chunk": 4 * (step - previous)}})
        previous = step
    return store


NO_DIFF = lambda a, b: (0.0, 1.0)  # noqa: E731  (adapter tensors need torch; the image suite compares real ones)


def cmp(tmp_path, whole=None, chunked=None, adapter_diff=NO_DIFF):
    import qualification as q
    make_run(tmp_path / "w", "whole", chunks=(4,), **(whole or {}))
    make_run(tmp_path / "c", "chunked", **(chunked or {}))
    return q.compare(tmp_path / "w", "whole", tmp_path / "c", "chunked", adapter_diff=adapter_diff)


