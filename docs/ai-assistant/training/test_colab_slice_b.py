LOCK_HEADER = ("# This file was autogenerated by uv via the following command:\n"
               "#    uv pip compile x.in --python-version 3.12 --python-platform x86_64-unknown-linux-gnu -o x.lock\n")


def write_lock(tmp_path, pins):
    path = tmp_path / "requirements-colab-cuda.lock"
    path.write_text(LOCK_HEADER + "".join(f"{k}=={v} \\\n    --hash=sha256:{'0' * 64}\n" for k, v in pins.items()),
                    encoding="utf-8")
    return path


PINS = {name: "1.0.0" for name in colab_env.KEY_PACKAGES}
PINS.update({"torch": "2.7.0+cu126", "nvidia-cudnn-cu12": "9.5.1.17", "triton": "3.3.0"})


def matching_record(tmp_path, torch_stub=None, **override):
    lock = write_lock(tmp_path, PINS)
    rec = colab_env.record(torch=torch_stub or FakeTorch(), smi=None, lock_path=lock,
                           version=lambda name: PINS.get(name))
    rec.update({"python": "3.12.4", "system": "Linux", "machine": "x86_64"}, **override)
    rec["environment_id"] = colab_env.environment_id(rec)
    return rec, lock


